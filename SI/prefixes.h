/// @file   SI/prefixes.h
/// @brief  Defines the 24 SI prefixes

#pragma once
#include <SI/units.h>

namespace SI { namespace prefix {

	const dimensionless quetta = 1e30; // 'Q' prefix
	const dimensionless ronna  = 1e27; // 'R' prefix
	const dimensionless yotta  = 1e24; // 'Y' prefix
	const dimensionless zetta  = 1e21; // 'Z' prefix
	const dimensionless exa    = 1e18; // 'E' prefix
	const dimensionless peta   = 1e15; // 'P' prefix
	const dimensionless tera   = 1e12; // 'T' prefix
	const dimensionless giga   = 1e9;  // 'G' prefix
	const dimensionless mega   = 1e6;  // 'M' prefix
	const dimensionless kilo   = 1e3;  // 'k' prefix
	const dimensionless hecto  = 1e2;  // 'h' prefix
	const dimensionless deca   = 1e1;  // 'da' prefix

	const dimensionless deci   = 1e-1; // 'd' prefix
	const dimensionless centi  = 1e-2; // 'c' prefix
	const dimensionless milli  = 1e-3; // 'm' prefix
	const dimensionless micro  = 1e-6; // 'µ' prefix
	const dimensionless nano   = 1e-9; // 'n' prefix
	const dimensionless pico   = 1e-12;// 'p' prefix
	const dimensionless femto  = 1e-15;// 'f' prefix
	const dimensionless atto   = 1e-18;// 'a' prefix
	const dimensionless zepto  = 1e-21;// 'z' prefix
	const dimensionless yocto  = 1e-24;// 'y' prefix
	const dimensionless ronto  = 1e-27;// 'r' prefix
	const dimensionless quecto = 1e-30;// 'q' prefix

} } // end of namespace SI
